using Newtonsoft.Json;
using System;

namespace ct._Core.Repo.Resource
{
    public interface IEntity
    {
        string Id { get; set; }
        string OwnerId { get; set; }
        string ParentId { get; set; }
    }

    public interface IAudit
    {
        DateTime CreatedOn { get; set; }
        string CreatedBy { get; set; }
        DateTime? ModifiedOn { get; set; }
        string ModifiedBy { get; set; }
    }

    [Serializable]
    public abstract class Entity : IEntity, IAudit
    {
        //IEntity
        public string Id { get; set; }
        public string OwnerId { get; set; }
        public string ParentId { get; set; }

        //Audit entries
        public DateTime CreatedOn { get; set; }
        public string CreatedBy { get; set; }
        public DateTime? ModifiedOn { get; set; }
        public string ModifiedBy { get; set; }
        [JsonIgnore]
        /// <summary>
        /// Set to true if the audit entries are set directly and not through the PostgreSQL session audit hook
        /// </summary>
        public bool Audited { get; set; }

        public Entity()
        {
            Id = string.Empty; //PostgreSQL document id is generated when empty. https://ravendb.net/docs/article-page/4.0/http/client-api/document-identifiers/working-with-document-identifiers#autogenerated-ids
            OwnerId = string.Empty;
            ParentId = string.Empty;
            CreatedOn = DateTime.MinValue;
        }

        public string SetId(string id = "")
        {
            var guid = Guid.Empty;
            if (!string.IsNullOrEmpty(id)) Guid.TryParse(id, out guid);
            Id = guid == Guid.Empty ? Guid.NewGuid().ToString() : guid.ToString();
            return Id;
        }

        public virtual void SetOwner(string ownerId)
        {
            OwnerId = ownerId;
        }

        public virtual void SetParent(string parentId)
        {
            ParentId = parentId;
        }

        public virtual void Audit(IAudit audit)
        {
            if (audit == null) return;
            CreatedOn = audit.CreatedOn;
            CreatedBy = audit.CreatedBy;
            ModifiedOn = audit.ModifiedOn;
            ModifiedBy = audit.ModifiedBy;
            Audited = true;
        }
    }

    [Serializable]
    public class Address
    {
        public Address()
        {
        }

        /// <summary>
        ///     In case the address is provided as a single line, we'd store it in Line1
        /// </summary>
        /// <param name="address"></param>
        public Address(string address)
        {
            Line1 = address;
        }

        public LocationType Location { get; set; }

        public string Line1 { get; set; }
        public string Line2 { get; set; }
        public string City { get; set; }
        public string State { get; set; }
        public string Country { get; set; }
        public string Pincode { get; set; }

        public DateTime? ArchivedOn { get; set; }

        public AddressStatus Status { get; set; }

        public override string ToString()
        {
            var result = Line1;
            result += string.IsNullOrWhiteSpace(Line2) ? string.Empty : " , " + Line2;
            result += string.IsNullOrWhiteSpace(City) ? string.Empty : " , " + City;
            result += string.IsNullOrWhiteSpace(State) ? string.Empty : " , " + State;
            result += string.IsNullOrWhiteSpace(Country) ? string.Empty : " , " + Country;
            result += string.IsNullOrWhiteSpace(Pincode) ? string.Empty : " , " + Pincode;
            return result;
        }
    }
    public enum AddressStatus
    {
        Unknown = -1,
        Active = 1,
        Archived = 99
    }
    public enum LocationType
    {
        Unknown = -1,
        Personal = 10,
        Home = 20,
        Office = 30,
        Other = 40,
        Institute = 50
    }

    [Serializable]
    public class Contact
    {
        public Contact()
        {
            Status = ContactStatus.Active;
            Location = LocationType.Personal;
            Primary = false;
            Info = string.Empty;
        }

        public ContactTypeEnum ContactType { get; set; }
        public LocationType Location { get; set; }
        public string Info { get; set; }
        public DateTime? ArchivedOn { get; set; }
        public ContactStatus Status { get; set; }
        public string Notes { get; set; }
        public bool Primary { get; set; }
    }
    public enum ContactStatus { Unknown = -1, Active = 1, Archived = 99, Disabled = 90 }
    public enum ContactTypeEnum { Unknown = -1, Email = 10, Mobile = 20, Phone = 30, Website = 40, Social = 50 }

    public class Occupation
    {
        public string Title { get; set; }
        public string Particulars { get; set; }
        public DateTime AsOn { get; set; }
    }
}
